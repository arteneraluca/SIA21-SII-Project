CREATE OR REPLACE VIEW GAMES_V AS
SELECT
	BGG_ID,
	NAME,
	YEAR_PUBLISHED,
	MIN_PLAYERS,
	MAX_PLAYERS,
	AVG_RATING
FROM GAMES;

CREATE OR REPLACE VIEW TOP_GAMES_V AS
SELECT
	BGG_ID,
	NAME,
	YEAR_PUBLISHED,
	MIN_PLAYERS,
	MAX_PLAYERS,
	AVG_RATING
FROM GAMES
WHERE AVG_RATING >= 6
ORDER BY AVG_RATING DESC;

CREATE OR REPLACE VIEW GAME_RATING_STATS_V AS
SELECT
	COUNT(*) AS GAME_COUNT,
	ROUND(AVG(AVG_RATING), 4) AS AVERAGE_RATING,
	MIN(AVG_RATING) AS MINIMUM_RATING,
	MAX(AVG_RATING) AS MAXIMUM_RATING
FROM GAMES;

CREATE OR REPLACE VIEW PLAYER_COUNT_STATS_V AS
SELECT
	MIN_PLAYERS,
	MAX_PLAYERS,
	COUNT(*) AS GAME_COUNT,
	ROUND(AVG(AVG_RATING), 4) AS AVERAGE_RATING
FROM GAMES
GROUP BY MIN_PLAYERS, MAX_PLAYERS;

