CREATE TABLE GAMES
(
    BGG_ID         NUMBER PRIMARY KEY,
    NAME           VARCHAR2(500),
    YEAR_PUBLISHED NUMBER,
    MIN_PLAYERS    NUMBER,
    MAX_PLAYERS    NUMBER,
    AVG_RATING     NUMBER(10, 5)
);

CREATE TABLE THEMES
(
    BGG_ID NUMBER NOT NULL,
    THEME  VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_THEMES PRIMARY KEY (BGG_ID, THEME)
);

CREATE TABLE USER_RATINGS
(
    ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BGG_ID   NUMBER NOT NULL,
    RATING   NUMBER(3, 1),
    USERNAME VARCHAR2(100)
);

CREATE TABLE GAMES_EXT
(
    BGG_ID         NUMBER,
    NAME           VARCHAR2(500),
    YEAR_PUBLISHED NUMBER,
    MIN_PLAYERS    NUMBER,
    MAX_PLAYERS    NUMBER,
    AVG_RATING     NUMBER(10, 5)
)
ORGANIZATION EXTERNAL
(
    TYPE ORACLE_LOADER
    DEFAULT DIRECTORY SIA_DATA_DIR
    ACCESS PARAMETERS
    (
        RECORDS DELIMITED BY NEWLINE
        LOGFILE SIA_LOG_DIR:'games_ext.log'
        BADFILE SIA_LOG_DIR:'games_ext.bad'
        DISCARDFILE SIA_LOG_DIR:'games_ext.dsc'
        SKIP 1
        FIELDS TERMINATED BY ',' OPTIONALLY ENCLOSED BY '"'
        MISSING FIELD VALUES ARE NULL
        (
            BGG_ID,
            NAME,
            YEAR_PUBLISHED,
            MIN_PLAYERS,
            MAX_PLAYERS,
            AVG_RATING
        )
    )
    LOCATION ('games_small.csv')
)
REJECT LIMIT UNLIMITED;

